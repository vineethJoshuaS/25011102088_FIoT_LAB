/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART1_UART_Init();
  MX_USART2_UART_Init();
  
  /* USER CODE BEGIN 2 */
  uint8_t c;

  HAL_Delay(2000);

  // 1. Test AT Command
  HAL_UART_Transmit(&huart2, (uint8_t*)"AT\r\n", 4, 1000);
  while (HAL_UART_Receive(&huart2, &c, 1, 2000) == HAL_OK)
  {
    HAL_UART_Transmit(&huart1, &c, 1, 1000);
  }

  HAL_Delay(1000);

  // 2. Set Station Mode
  HAL_UART_Transmit(&huart2, (uint8_t*)"AT+CWMODE=1\r\n", 13, 1000);
  while (HAL_UART_Receive(&huart2, &c, 1, 2000) == HAL_OK)
  {
    HAL_UART_Transmit(&huart1, &c, 1, 1000);
  }

  HAL_Delay(1000);

  // 3. Connect to Wi-Fi (Vivo V50)
  HAL_UART_Transmit(&huart2, (uint8_t*)"AT+CWJAP=\"Vivo V50\",\"pass1441\"\r\n", 33, 1000);
  while (HAL_UART_Receive(&huart2, &c, 1, 10000) == HAL_OK)
  {
    HAL_UART_Transmit(&huart1, &c, 1, 1000);
  }

  HAL_Delay(1000);

  // 4. Get IP Address
  HAL_UART_Transmit(&huart2, (uint8_t*)"AT+CIFSR\r\n", 10, 1000);
  while (HAL_UART_Receive(&huart2, &c, 1, 3000) == HAL_OK)
  {
    HAL_UART_Transmit(&huart1, &c, 1, 1000);
  }
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* Bridge serial characters between PC (USART1) and ESP8266 (USART2) */
    if (HAL_UART_Receive(&huart1, &c, 1, 10) == HAL_OK)
    {
      HAL_UART_Transmit(&huart2, &c, 1, 10);
    }
    if (HAL_UART_Receive(&huart2, &c, 1, 10) == HAL_OK)
    {
      HAL_UART_Transmit(&huart1, &c, 1, 10);
    }
  }
  /* USER CODE END 3 */
}

